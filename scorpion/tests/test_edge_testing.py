# ─── regressEdges ────────────────────────────────────────────────────────────

class TestRegressEdges:
    """Linear regression across ordered conditions."""

    def test_regress_edges(self, networks_df):
        r_ref = pd.read_csv(DATA_DIR / "ref_regressEdges.csv")
        normal_cols = sorted([c for c in networks_df.columns if c.endswith("--N")])
        border_cols = sorted([c for c in networks_df.columns if c.endswith("--B")])
        tumor_cols = sorted([c for c in networks_df.columns if c.endswith("--T")])

        py_res = regress_edges(
            networks_df,
            ordered_groups={
                "Normal": normal_cols,
                "Border": border_cols,
                "Tumor": tumor_cols,
            },
        )

        _assert_frames_close(
            py_res, r_ref,
            ["slope", "intercept", "rSquared", "fStatistic",
             "pValue", "pAdj", "meanEdge",
             "meanNormal", "meanBorder", "meanTumor"],
        )


# ─── Input validation ────────────────────────────────────────────────────────

class TestInputValidation:

    def test_missing_group1(self, networks_df):
        with pytest.raises(ValueError, match="group1"):
            _test_edges(networks_df, test_type="single", group1=None)

    def test_missing_group2_two_sample(self, networks_df):
        with pytest.raises(ValueError, match="group2"):
            _test_edges(networks_df, test_type="two.sample",
                       group1=["P1--T"], group2=None)

    def test_paired_length_mismatch(self, networks_df):
        with pytest.raises(ValueError, match="same length"):
            _test_edges(networks_df, test_type="two.sample",
                       group1=["P1--T", "P2--T"], group2=["P1--N"],
                       paired=True)

    def test_regress_needs_two_conditions(self, networks_df):
        with pytest.raises(ValueError, match="at least 2"):
            regress_edges(networks_df, ordered_groups={"A": ["P1--T"]})
