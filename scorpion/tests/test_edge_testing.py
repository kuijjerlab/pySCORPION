"""
Tests for scorpion.edge_testing (test_edges and regress_edges).

Compares Python output against R SCORPION reference data generated by
tests/generate_edge_test_data.R.
"""

import numpy as np
import pandas as pd
import pytest
from pathlib import Path

from scorpion.edge_testing import test_edges as _test_edges, regress_edges

DATA_DIR = Path(__file__).parent / "data"


@pytest.fixture(scope="module")
def networks_df():
    return pd.read_csv(DATA_DIR / "ref_networks_df.csv")


# ─── helpers ─────────────────────────────────────────────────────────────────

def _assert_frames_close(py_df, r_df, numeric_cols, atol=1e-6, rtol=1e-5):
    """Assert numeric columns of two DataFrames match within tolerance."""
    assert len(py_df) == len(r_df), f"Row count mismatch: {len(py_df)} vs {len(r_df)}"
    # Align by tf + target
    py_sorted = py_df.sort_values(["tf", "target"]).reset_index(drop=True)
    r_sorted = r_df.sort_values(["tf", "target"]).reset_index(drop=True)
    for col in numeric_cols:
        py_vals = py_sorted[col].to_numpy(dtype=float)
        r_vals = r_sorted[col].to_numpy(dtype=float)
        # Both NaN → ok; one NaN → fail
        both_nan = np.isnan(py_vals) & np.isnan(r_vals)
        either_nan = np.isnan(py_vals) | np.isnan(r_vals)
        mismatch_nan = either_nan & ~both_nan
        assert not mismatch_nan.any(), (
            f"Column '{col}': NaN mismatch at rows {np.where(mismatch_nan)[0]}"
        )
        valid = ~either_nan
        if valid.any():
            np.testing.assert_allclose(
                py_vals[valid], r_vals[valid],
                atol=atol, rtol=rtol,
                err_msg=f"Column '{col}' values differ",
            )


# ─── testEdges: single-sample ────────────────────────────────────────────────

class TestEdgesSingle:
    """Single-sample t-test (edges vs zero)."""

    def test_single_with_empirical_null(self, networks_df):
        """testEdges(single, moderateVariance=T, empiricalNull=T)"""
        r_ref = pd.read_csv(DATA_DIR / "ref_testEdges_single.csv")
        tumor_cols = [c for c in networks_df.columns if c.endswith("--T")]

        py_res = _test_edges(
            networks_df, test_type="single", group1=tumor_cols,
            moderate_variance=True, empirical_null=True,
        )

        _assert_frames_close(
            py_res, r_ref,
            ["meanEdge", "tStatistic", "pValue", "pAdj"],
        )

    def test_single_no_empirical_null(self, networks_df):
        """testEdges(single, moderateVariance=T, empiricalNull=F)"""
        r_ref = pd.read_csv(DATA_DIR / "ref_testEdges_single_noemp.csv")
        tumor_cols = [c for c in networks_df.columns if c.endswith("--T")]

        py_res = _test_edges(
            networks_df, test_type="single", group1=tumor_cols,
            moderate_variance=True, empirical_null=False,
        )

        _assert_frames_close(
            py_res, r_ref,
            ["meanEdge", "tStatistic", "pValue", "pAdj"],
        )


